import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { access, copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const project = join(root, 'tests/dotnet/Shotx.csproj');
const unityPackage = join(root, 'packages/shotx-unity');
const plugins = join(unityPackage, 'Runtime/Plugins');

// Unity's .NET Standard 2.1 profile supplies these assemblies; Newtonsoft comes from UPM.
const suppliedByUnity = new Set([
    'Newtonsoft.Json.dll',
    'System.Buffers.dll',
    'System.Memory.dll',
    'System.Numerics.Vectors.dll',
    'System.Threading.Tasks.Extensions.dll'
]);

execFileSync('dotnet', ['restore', project, '--locked-mode'], { stdio: 'inherit' });
const assets = JSON.parse(await readFile(join(dirname(project), 'obj/project.assets.json'), 'utf8'));
const target = assets.targets['.NETStandard,Version=v2.1'];
if (!target) throw new Error('Expected .NET Standard 2.1 dependency assets');

const assemblies = new Map();
const notices = new Map();
for (const [name, dependency] of Object.entries(target)) {
    const runtime = Object.keys(dependency.runtime ?? {}).filter(path => path.endsWith('.dll') && !suppliedByUnity.has(path.split('/').at(-1)));
    if (runtime.length === 0) continue;

    const library = assets.libraries[name];
    const packageRoot = Object.keys(assets.packageFolders).find(folder =>
        existsSync(resolve(folder, library.path)));
    if (!packageRoot) throw new Error(`Restored package not found: ${name}`);
    const directory = resolve(packageRoot, library.path);

    for (const path of runtime) {
        const filename = path.split('/').at(-1);
        if (assemblies.has(filename)) throw new Error(`Duplicate assembly: ${filename}`);
        const source = join(directory, path);
        await access(source);
        assemblies.set(filename, source);
    }

    let license;
    if (name.startsWith('SocketIO')) {
        const nuspec = (await readdir(directory)).find(path => path.endsWith('.nuspec'));
        const metadata = await readFile(join(directory, nuspec), 'utf8');
        const commit = metadata.match(/<repository[^>]*commit="([a-f0-9]{40})"/)?.[1];
        if (!commit) throw new Error(`Missing upstream commit: ${name}`);
        const response = await fetch(`https://raw.githubusercontent.com/doghappy/socket.io-client-csharp/${commit}/LICENSE`);
        if (!response.ok) throw new Error(`Could not download license for ${name}: ${response.status}`);
        license = await response.text();
    } else {
        license = await readFile(join(directory, 'LICENSE.TXT'), 'utf8');
        const thirdParty = await readFile(join(directory, 'THIRD-PARTY-NOTICES.TXT'), 'utf8');
        license += `\n${thirdParty}`;
    }
    license = license.replace(/\r\n/g, '\n').trim();
    if (!notices.has(license)) notices.set(license, []);
    notices.get(license).push(name);
}

// Do not leave stale DLLs when dependency versions or the Unity profile change.
await mkdir(plugins, { recursive: true });
for (const file of await readdir(plugins)) {
    if (file.endsWith('.dll') && !assemblies.has(file)) {
        throw new Error(`Stale DLL: ${file}. Remove it and its .meta before regenerating.`);
    }
}
for (const [filename, source] of assemblies) {
    await copyFile(source, join(plugins, filename));
    await writeMeta(join(plugins, filename));
}
await writeMeta(plugins);

const noticePath = join(unityPackage, 'Third Party Notices.md');
const content = ['# Third-party dependencies', '', 'Generated by `pnpm build:unity-deps` from the locked NuGet dependencies.', ''];
for (const [license, packages] of notices) {
    content.push(`## ${packages.join(', ')}`, '', '```text', license, '```', '');
}
await writeFile(noticePath, content.join('\n'));
await writeMeta(noticePath);
console.log(`Bundled ${assemblies.size} assemblies in packages/shotx-unity/Runtime/Plugins`);

async function writeMeta(path) {
    const relative = path.slice(unityPackage.length + 1).replaceAll('\\', '/');
    const guid = createHash('sha256').update(`com.clasen.shotx/${relative}`).digest('hex').slice(0, 32);
    const folder = path === plugins ? 'folderAsset: yes\n' : '';
    await writeFile(`${path}.meta`, `fileFormatVersion: 2\nguid: ${guid}\n${folder}`);
}
